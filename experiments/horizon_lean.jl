# Exports the trial tables of experiments/results-horizon.json to formal/gen/Trials.lean and compares Lean's own
# checkSelfProducing / checkValueNeeded (formal/LabCircuit.lean, valueNeeded_iff_check, selfProducing_iff_check) with
# the Julia verdicts. Usage: julia --project=. experiments/horizon_lean.jl   (needs formal/.olean/LabCircuit.olean,
# built by sh audit/dc_lean.sh)
using JSON
const LAB = normpath(joinpath(@__DIR__, ".."))
r = JSON.parse(read(joinpath(LAB, "experiments", "results-horizon.json"), String))
# structure table: intact = own activity (sensors silenced, abundant), ablated = every unit silenced
# survival table: intact = as it is, ablated = value-tracking units silenced (only where they exist)
tab(rows) = "(fun (i : Fin $(length(rows))) (v : ERIEC.Agency.Variant) => match v with | .intact => (#[" *
    join([string(x[1]) for x in rows], ", ") * "])[i.val]! | .ablated => (#[" * join([string(x[2]) for x in rows], ", ") * "])[i.val]!)"
io = IOBuffer(); expect = Any[]
println(io, "-- Generated by experiments/horizon_lean.jl: the D6 variant's trial tables, judged by Lean's own checks.")
println(io, "import LabCircuit\nopen BridgeLab\n")
for x in r["runs"]
    println(io, "#eval checkSelfProducing $(tab(x["table_structure"]))")
    push!(expect, x["self_producing_L3"])
    if !isempty(x["value_tracking"])
        println(io, "#eval checkValueNeeded $(tab(x["table_survival"]))")
        push!(expect, x["value_needed"])
    end
end
write(joinpath(LAB, "formal", "gen", "Trials.lean"), String(take!(io)))
bp = joinpath(homedir(), "bridge-protocol"); ol = joinpath(LAB, "formal", ".olean")
out = cd(bp) do
    read(`lake env sh -c "LEAN_PATH=\"\$LEAN_PATH:$ol\" lean \"$(joinpath(LAB, "formal", "gen", "Trials.lean"))\""`, String)
end
got = [l == "true" for l in split(strip(out), "\n")]
same = got == expect
println("Lean on $(length(got)) tables: ", same ? "identical to Julia" : "DIFFERENT from Julia",
    " (true $(count(got)), false $(count(!, got)); value-needed tables $(count(x -> !isempty(x["value_tracking"]), r["runs"])))")
same || exit(1)
